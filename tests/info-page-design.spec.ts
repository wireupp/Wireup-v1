import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`Info page uses the Blueprint palette and remains navigable at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(120000)
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Info design preview', board: 'arduino-uno' } })).json()
  await page.setViewportSize({ width, height: 900 })
  await page.goto(`/project/${project.id}?section=info`)
  const info = page.getByRole('region', { name: 'Info project details' })
  await expect(info.getByRole('heading', { name: 'Project overview' })).toBeVisible({ timeout: 30000 })
  await expect(info).toContainText('Not compiled')
  await expect(info).toContainText('No compiled artifact')
  const container = page.locator('.project-details.pd-embedded.pd-info')
  expect(await container.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(242, 242, 247)')
  expect(await container.locator('.pd-header').evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(64, 62, 106)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(`info-embedded-${width}.png`) })
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('menuitem', { name: 'Build Guide' }).click()
  await expect(page.getByRole('region', { name: 'Interactive Build Guide' }).getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('menuitem', { name: 'Info', exact: true }).click()
  await expect(info.getByRole('heading', { name: 'Project overview' })).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'Project details', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Info design preview' })
  await expect(dialog).toBeVisible()
  expect(await dialog.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(242, 242, 247)')
  expect(await dialog.getByRole('heading', { name: 'Info design preview' }).evaluate(element => getComputedStyle(element).textTransform)).toBe('none')
  await dialog.screenshot({ path: testInfo.outputPath(`info-dialog-${width}.png`) })
  await dialog.getByRole('button', { name: 'Parts', exact: true }).click()
  await expect(dialog.getByRole('region', { name: 'Parts project details' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Info', exact: true }).press('Enter')
  await expect(dialog.getByRole('region', { name: 'Info project details' })).toContainText('Compile support')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
