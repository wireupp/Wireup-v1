import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`Build Guide follows the project documentation design at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(180000)
  const project = await (await request.post('/api/hardware/projects', { data: { name: 'Documentation design', board: 'arduino-uno' } })).json()
  await page.setViewportSize({ width, height: 900 })
  await page.goto(`/project/${project.id}?section=guide`)
  const guide = page.getByRole('region', { name: 'Interactive Build Guide' })
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  await expect(guide).toContainText('Documentation design')
  expect(await guide.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(242, 242, 242)')
  await guide.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(guide.getByRole('heading', { level: 2 })).toBeVisible()
  const steps = guide.getByRole('navigation', { name: 'Build guide steps' }).getByRole('button')
  await expect(steps.nth(1)).toHaveAttribute('aria-current', 'step')
  expect(await steps.first().evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect(steps.nth(4)).toBeEnabled()
  await steps.nth(4).press('Enter')
  await expect(steps.nth(4)).toHaveAttribute('aria-current', 'step')
  await expect(guide.locator('.build-guide-code summary')).toContainText('Saved sketch')
  await expect(guide.getByLabel('Saved firmware source')).toBeVisible()
  await guide.getByRole('checkbox').first().click()
  await expect(guide.getByRole('checkbox').first()).toBeChecked()
  await guide.getByRole('button', { name: 'Open Wiring', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Project sections' }).getByRole('button', { name: 'Wiring/Simulation' })).toHaveAttribute('aria-pressed', 'true', { timeout: 15000 })
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('button', { name: 'More', exact: true }).click()
  await page.getByRole('navigation', { name: 'Project sections' }).getByRole('menuitem', { name: 'Build Guide' }).click()
  await expect(guide.getByRole('progressbar')).toBeVisible({ timeout: 30000 })
  await expect(steps.nth(4)).toHaveAttribute('aria-current', 'step', { timeout: 30000 })
  if (width < 600) await expect.poll(() => steps.nth(4).evaluate(element => {
    const viewport = element.closest('ol')!.getBoundingClientRect()
    const active = element.getBoundingClientRect()
    return active.left >= viewport.left && active.right <= viewport.right + 1
  })).toBe(true)
  await expect(guide.getByRole('checkbox').first()).toBeChecked({ timeout: 30000 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(`build-guide-design-${width}.png`) })
})
